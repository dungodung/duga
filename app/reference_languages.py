"""The languages a contributor translates *from*: when they add a missing
label or description, the edit page shows what Wikidata already says
about the item in each of them. Chosen on the account page, up to
MAX_LANGUAGES, from every language Wikidata accepts terms in
(data/wikidata_term_languages.json, regenerated by
scripts/fetch_term_languages.py).

Stored in contributor.languages_json as {"reference": [codes]}, in the
order they were added. A contributor who has never chosen gets English,
which is what the edit page always showed before there was a choice; one
who removes every language gets none, because that is what they asked
for.
"""
import json
import os
import re
from functools import lru_cache

from . import i18n

MAX_LANGUAGES = 5
DEFAULT = ("en",)
DATA_FILE = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "data", "wikidata_term_languages.json")

# "Serbian — српски / srpski (sr)": the trailing code is what the picker's
# <datalist> option carries, so a choice from the list resolves exactly
# even when two languages share a name.
_TRAILING_CODE = re.compile(r"\(([a-z0-9-]+)\)\s*$")


@lru_cache(maxsize=1)
def _table():
    with open(DATA_FILE, encoding="utf-8") as fh:
        return json.load(fh)


def is_known(code):
    return code in _table()


def name(code, lang):
    """The language's name in `lang`, else in English, else its autonym."""
    entry = _table().get(code)
    if entry is None:
        return code
    names = entry["names"]
    return names.get(lang) or names.get(i18n.FALLBACK_LANG) or entry["autonym"]


def autonym(code):
    entry = _table().get(code)
    return entry["autonym"] if entry else code


def option_text(code, lang):
    """One <datalist> option, holding every string somebody might type to
    find it: the name in the interface language, the autonym when it
    differs, and the code. Some browsers match only an option's value, not
    its label, so all of it goes in the value."""
    shown = name(code, lang)
    own = autonym(code)
    if own.lower() != shown.lower():
        shown = f"{shown} — {own}"
    return f"{shown} ({code})"


def options(lang):
    """Every language, sorted by its name in the interface language."""
    codes = sorted(_table(), key=lambda code: (name(code, lang).casefold(), code))
    return [option_text(code, lang) for code in codes]


def resolve(text, lang):
    """The code someone meant by what they typed or picked, or None.

    Accepts a picked option ("Serbian — српски / srpski (sr)"), a bare code
    ("sr"), or a name or autonym typed out in full, ignoring case."""
    text = (text or "").strip()
    if not text:
        return None
    match = _TRAILING_CODE.search(text)
    if match and is_known(match.group(1)):
        return match.group(1)
    folded = text.casefold()
    if is_known(folded):
        return folded
    for code in _table():
        if folded in (name(code, lang).casefold(), name(code, i18n.FALLBACK_LANG).casefold(), autonym(code).casefold()):
            return code
    return None


def chosen(contributor):
    """The contributor's languages, in the order they added them."""
    if contributor is None or not contributor.languages_json:
        return list(DEFAULT)
    try:
        stored = json.loads(contributor.languages_json).get("reference")
    except (ValueError, AttributeError):
        return list(DEFAULT)
    if stored is None:
        return list(DEFAULT)
    return [code for code in stored if is_known(code)][:MAX_LANGUAGES]


def save(contributor, codes):
    try:
        data = json.loads(contributor.languages_json or "{}")
        if not isinstance(data, dict):
            data = {}
    except ValueError:
        data = {}
    data["reference"] = list(codes)[:MAX_LANGUAGES]
    contributor.languages_json = json.dumps(data)
